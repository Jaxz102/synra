/**
 * Regenerates scripts/neon-schema.sql from drizzle/*.sql: `bun run db:neon-schema`.
 *
 * Each migration is wrapped in a block that runs only if drizzle's journal does not list it yet, then records it
 * there with the same hash (sha256 of the file) and created_at (`when` in drizzle/meta/_journal.json) that
 * `bun run db:migrate` would write. So the SQL file and db:migrate can be mixed freely on the same database.
 */
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"

const journal = JSON.parse(
  readFileSync("drizzle/meta/_journal.json", "utf8")
) as {
  entries: { idx: number; when: number; tag: string }[]
}

const blocks = journal.entries.map(({ tag, when }) => {
  const sql = readFileSync(`drizzle/${tag}.sql`, "utf8")
  const hash = createHash("sha256").update(sql).digest("hex")
  const statements = sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean)
  for (const s of statements)
    if (s.includes("$stmt$")) throw new Error(`${tag} contains "$stmt$"`)
  return `-- ${tag}
DO $migration$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM "drizzle"."__drizzle_migrations" WHERE "hash" = '${hash}') THEN
${statements.map((s) => `\t\tEXECUTE $stmt$${s}$stmt$;`).join("\n")}
		INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") VALUES ('${hash}', ${when});
	END IF;
END $migration$;`
})

const out = `-- Synra production schema for Neon (Postgres). GENERATED by scripts/neon-schema.ts — do not edit.
--
-- Applies every migration in drizzle/ (${journal.entries.map((e) => e.tag).join(", ")}) that the database's
-- drizzle journal does not list yet, and records it there exactly as \`bun run db:migrate\` would. Works on an empty
-- database and on one already partly migrated; safe to run more than once.
--
-- Usage: paste into the Neon SQL editor, or
--   psql "$PRODUCTION_DATABASE_URL" -f scripts/neon-schema.sql
-- (equivalent: NODE_ENV=production bun run db:migrate)
--
-- When lib/db/schema.ts changes: \`bun run db:generate\`, then \`bun run db:neon-schema\` to refresh this file.

BEGIN;

CREATE SCHEMA IF NOT EXISTS "drizzle";
CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (
	"id" serial PRIMARY KEY,
	"hash" text NOT NULL,
	"created_at" bigint
);

${blocks.join("\n\n")}

COMMIT;
`
writeFileSync("scripts/neon-schema.sql", out)
console.log(
  `[synra] wrote scripts/neon-schema.sql (${journal.entries.length} migrations)`
)
